def main() -> int:
    db = SessionLocal()
    try:
        # 1. 下架两条测试残留商品，避免出现在商品列表
        db.execute(
            update(Product)
            .where(Product.id.in_([34, 35]))
            .values(is_active=False)
        )

        # 2. 已有商品图片统一切到本地路径
        products = db.scalars(select(Product).where(Product.id <= 33)).all()
        for product in products:
            path = f"{IMAGE_PREFIX}/p{product.id}.png"
            product.main_image = path
            product.images = [path]
        db.flush()

        # 3. 新增商品（同名跳过，幂等）
        created = 0
        for sub_name, items in NEW_PRODUCTS.items():
            sub = db.scalar(select(Category).where(Category.name == sub_name))
            if not sub:
                raise RuntimeError(f"二级类目不存在：{sub_name}")
            for name, desc, code, attrs, price, stock, sales in items:
                exists = db.scalar(select(Product).where(Product.name == name))
                if exists:
                    continue
                product = Product(
                    name=name,
                    category_id=sub.id,
                    description=desc,
                    main_image="",
                    images=[],
                    is_active=True,
                    sales_count=sales,
                )
                db.add(product)
                db.flush()
                path = f"{IMAGE_PREFIX}/p{product.id}.png"
                product.main_image = path
                product.images = [path]
                db.add(
                    Sku(
                        product_id=product.id,
                        sku_code=code,
                        attrs=attrs,
                        attrs_key=build_attrs_key(attrs),
                        price=price,
                        stock=stock,
                        is_active=True,
                    )
                )
                created += 1

        db.commit()
        total = db.scalar(
            select(func.count()).select_from(Product).where(Product.is_active.is_(True))
        ) or 0
        print(f"新增 {created} 个商品；当前在售商品 {total} 个（已下架测试商品 34/35）")
        return 0
    finally:
        db.close()


if __name__ == "__main__":
    raise SystemExit(main())
